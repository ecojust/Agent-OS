#!/usr/bin/env python3
"""Bounded Perfetto capture on the dedicated synthetic emulator only."""

import argparse
import gzip
import hashlib
import json
from pathlib import Path
import re
import resource
import subprocess
import tempfile
import time

REMOTE_TRACE = "/data/misc/perfetto-traces/agentos-experience.pftrace"
RAW_LIMIT = 64 * 1024 * 1024
GZIP_LIMIT = 12 * 1024 * 1024
STATE_NAME = "trace-capture.json"


def adb(*arguments, timeout=10, check=True, input_text=None):
    return subprocess.run(["adb", *arguments], capture_output=True, text=True,
                          timeout=timeout, check=check, input=input_text)


def save(output, value):
    output.mkdir(parents=True, exist_ok=True)
    temporary = output / (STATE_NAME + ".tmp")
    temporary.write_text(json.dumps(value, sort_keys=True, indent=2) + "\n")
    temporary.replace(output / STATE_NAME)


def start(output):
    # The config is generated by the same pinned parser module used after capture.
    from experience_trace import trace_config
    config = trace_config(version=2)
    value = dict(schemaVersion=3, kind="agent-os-experience-trace-capture", status="failed",
                 pid=None, stopped=False, startMode=None, ready=False,
                 configVersion=2,
                 configDelivery="stdin", startStdout="", startStderr="", startExitCode=None,
                 config=config, trace=None, compressed=None, error=None)
    try:
        adb("shell", "rm", "-f", REMOTE_TRACE)
        help_result = adb("shell", "perfetto", "--help", check=False)
        mode = "--background-wait" if "--background-wait" in (help_result.stdout + help_result.stderr) else "--background"
        value["startMode"] = mode
        # Perfetto's documented Android interface accepts config on stdin.
        # /data/local/tmp config files are blocked by SELinux on older Android.
        result = adb("shell", "perfetto", "--txt", "-c", "-",
                     "-o", REMOTE_TRACE, mode, timeout=20, check=False, input_text=config)
        value.update(startExitCode=result.returncode,
                     startStdout=result.stdout.encode("utf-8")[:2048].decode("utf-8", "ignore"),
                     startStderr=result.stderr.encode("utf-8")[:2048].decode("utf-8", "ignore"))
        if result.returncode != 0:
            raise ValueError(f"perfetto_start_exit_{result.returncode}")
        text = result.stdout.strip()
        if not re.fullmatch(r"[1-9][0-9]{0,8}", text):
            raise ValueError("unexpected_perfetto_background_pid: " + text[:200])
        value["pid"] = int(text)
        # Android 11 only supports --background. Require a live process and a
        # first streamed file chunk; complete launch markers are checked later.
        deadline = time.monotonic() + 12
        while time.monotonic() < deadline:
            name = adb("shell", "cat", f"/proc/{value['pid']}/comm", check=False)
            if name.returncode != 0 or name.stdout.strip() != "perfetto":
                raise ValueError("perfetto_exited_during_start")
            size = adb("shell", "stat", "-c", "%s", REMOTE_TRACE, check=False)
            if size.returncode == 0 and size.stdout.strip().isdigit() and int(size.stdout) > 0:
                value.update(ready=True, status="recording")
                break
            time.sleep(0.2)
        if not value["ready"]:
            raise ValueError("perfetto_first_stream_timeout")
    except (OSError, ValueError, subprocess.SubprocessError) as error:
        value["error"] = str(error)[:500]
    save(output, value)
    return value["status"] == "recording"


def bounded_output():
    resource.setrlimit(resource.RLIMIT_FSIZE, (RAW_LIMIT + 1, RAW_LIMIT + 1))


def stop(output):
    state = output / STATE_NAME
    if not state.is_file() or state.is_symlink() or state.stat().st_size > 16384:
        raise ValueError("trace_capture_state_unavailable")
    value = json.loads(state.read_text())
    if value.get("status") not in ("recording", "failed") or value.get("pid") is None:
        return False
    value["status"] = "failed"
    try:
        pid = value["pid"]
        if type(pid) is not int or not 1 <= pid <= 999999999:
            raise ValueError("invalid_perfetto_pid")
        # Validate process identity before signalling: a reused PID must not be killed.
        name = adb("shell", "cat", f"/proc/{pid}/comm", check=False)
        if name.returncode != 0 or name.stdout.strip() != "perfetto":
            raise ValueError("perfetto_process_exited_before_stop")
        adb("shell", "kill", "-INT", str(pid))
        deadline = time.monotonic() + 20
        while time.monotonic() < deadline:
            result = adb("shell", "kill", "-0", str(pid), timeout=3, check=False)
            if result.returncode != 0:
                value["stopped"] = True
                break
            time.sleep(0.2)
        if not value["stopped"]:
            raise ValueError("perfetto_stop_timeout")
    except (OSError, ValueError, subprocess.SubprocessError) as error:
        value["error"] = str(error)[:500]
    try:
        # Preserve a readable bounded trace even when the recorder exited early.
        # Its failed capture status is never promoted by successful compression.
        with tempfile.TemporaryDirectory(prefix="experience-trace-") as temporary:
            raw = Path(temporary) / "trace.pftrace"
            with raw.open("wb") as stream:
                subprocess.run(["adb", "exec-out", "cat", REMOTE_TRACE], stdout=stream,
                               stderr=subprocess.DEVNULL, timeout=25, check=True,
                               preexec_fn=bounded_output)
            length = raw.stat().st_size
            if not 0 < length <= RAW_LIMIT:
                raise ValueError("trace_empty_or_exceeds_size_limit")
            if length == RAW_LIMIT:
                value["error"] = "trace_reached_size_limit"
            compressed = output / "trace.pftrace.gz"
            raw_hash = hashlib.sha256()
            with raw.open("rb") as source, compressed.open("wb") as target:
                with gzip.GzipFile(filename="", mode="wb", fileobj=target, mtime=0) as zipped:
                    while block := source.read(65536):
                        raw_hash.update(block)
                        zipped.write(block)
                        if target.tell() > GZIP_LIMIT:
                            raise ValueError("compressed_trace_exceeds_budget")
            if compressed.stat().st_size > GZIP_LIMIT:
                raise ValueError("compressed_trace_exceeds_budget")
            value.update(trace=dict(path="trace.pftrace", bytes=length, sha256=raw_hash.hexdigest()),
                         compressed=dict(path="trace.pftrace.gz", bytes=compressed.stat().st_size,
                                         sha256=hashlib.sha256(compressed.read_bytes()).hexdigest()),
                         status="collected" if value["stopped"] and value["error"] is None else "failed")
    except (OSError, ValueError, subprocess.SubprocessError) as error:
        value["error"] = str(error)[:500]
        # An incomplete file cannot masquerade as an archived trace.
        (output / "trace.pftrace.gz").unlink(missing_ok=True)
    save(output, value)
    return value["status"] == "collected"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mode", choices=("start", "stop"))
    parser.add_argument("--matrix-label", required=True, choices=tuple(map(str, range(30, 37))) + ("37.0",))
    args = parser.parse_args()
    output = Path("app-experience-evidence") / ("api-" + args.matrix_label)
    raise SystemExit(0 if (start if args.mode == "start" else stop)(output) else 1)


if __name__ == "__main__":
    main()
